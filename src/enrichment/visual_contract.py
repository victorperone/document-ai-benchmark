"""Data contracts for the visual enrichment worker protocol.

Defines the request and response dataclasses exchanged between
VisualWorkerClient (parent process) and visual_worker.py (child process)
over a JSON-Lines stdin/stdout channel.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class VisualRequest:
    """A single visual enrichment request sent to the worker process.

    Attributes:
        request_id: Unique identifier for this request, e.g. ``"p4-picture-2"``.
        operation: Processing operation to perform, e.g. ``"ocr_and_describe"``.
        image_base64: PNG image bytes encoded as base64. Cleared from memory
            after the payload is written to the worker's stdin.
        language: ISO 639-2 language code for OCR, e.g. ``"por"``.
        prompt: Text prompt forwarded to the vision-language model.
        page_number: 1-based page index from which this region was extracted.
        region_id: Identifier for the image region within its page.
    """

    request_id: str       # e.g. "p4-picture-2"
    operation: str        # "ocr_and_describe"
    image_base64: str     # PNG bytes encoded as base64; cleared after send
    language: str         # e.g. "por"
    prompt: str
    page_number: int
    region_id: str


@dataclass
class VisualResponse:
    """The enrichment result returned by the worker process.

    Attributes:
        request_id: Mirrors the ``request_id`` from the corresponding
            ``VisualRequest``.
        status: Outcome indicator — ``"success"`` or ``"error"``.
        ocr_text: Text extracted by PaddleOCR; empty string on failure.
        description: Visual description generated by SmolVLM; empty string
            on failure.
        ocr_engine: Name of the OCR engine used (e.g. ``"paddleocr"``).
        ocr_model: Model identifier or path used for OCR; may be empty.
        description_engine: Name of the VLM engine used (e.g. ``"smolvlm"``).
        description_model: Model path used for visual description.
        error_detail: Human-readable error message; empty string on success.
            May accumulate multiple partial failures separated by ``"; "``.
    """

    request_id: str
    status: str           # "success" | "error"
    ocr_text: str
    description: str
    ocr_engine: str
    ocr_model: str
    description_engine: str
    description_model: str
    error_detail: str = ""
